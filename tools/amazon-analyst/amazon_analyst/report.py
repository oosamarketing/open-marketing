"""Markdown report for a run: floors, top sellers, page-1 table, keyword tiers, optional LLM analysis."""
from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path

from . import config


def _money(v) -> str:
    return "" if v is None else f"{v:,.0f}"


def _cell(v) -> str:
    return "" if v is None else str(v)


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")[:60] or "run"


def build_report(run: dict, products: list[dict], candidates: list[dict], *, analysis: str = "") -> str:
    s = run.get("summary") or {}
    organic = [p for p in products if p.get("organic_position") is not None and not p.get("excluded")]
    page1 = [p for p in organic if p.get("page") == 1]
    top = sorted([p for p in organic if p.get("bought_past_month_min")], key=lambda p: -(p.get("revenue_min") or 0))[:10]
    lines = [
        f"# Amazon research: {run['keyword']} ({run['marketplace']})",
        "",
        f"Run #{run['id']} · {run['created_at'][:10]} · {run['pages_scraped']} pages · {run['products_found']} products "
        f"({run['sponsored_count']} sponsored-only) · research use only",
        "",
        "## Market floors",
        "",
        "Amazon's \"N+ bought in past month\" badge is a bucketed floor and is hidden under roughly 50 units a month, so every sum "
        "below is a lower bound. Revenue = floor × current retail price.",
        "",
        "| Scope | Listings with a badge | Units / month (floor) | Gross revenue / month (floor) |",
        "|---|---|---|---|",
        f"| Page 1 organic | {s.get('page1_units_known_count', 0)} of {s.get('page1_organic_count', 0)} | {_cell(s.get('page1_units_min_sum'))} | {_money(s.get('page1_revenue_min_sum'))} |",
        f"| All pages organic | {s.get('all_pages_units_known_count', 0)} of {len(organic)} | {_cell(s.get('all_pages_units_min_sum'))} | {_money(s.get('all_pages_revenue_min_sum'))} |",
        "",
        f"Median page-1 price {_cell(s.get('median_price'))} · median rating {_cell(s.get('median_rating'))} · median reviews {_cell(s.get('median_review_count'))}",
        "",
        "## Top sellers by revenue floor",
        "",
        "| # | ASIN | Brand | Units floor | Price | Revenue floor | Reviews | BSR | Title |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for p in top:
        lines.append(f"| {p['position']} | {p['asin']} | {p.get('brand_name', '')[:18]} | {p['bought_past_month_min']} | {_cell(p.get('price'))} | "
                     f"{_money(p.get('revenue_min'))} | {_cell(p.get('review_count'))} | {_cell(p.get('bsr_rank'))} | {p.get('title', '')[:60]} |")
    lines += ["", "## Page-1 organic results", "", "| Pos | ASIN | Brand | Price | Rating | Reviews | Units floor | BSR | Title |", "|---|---|---|---|---|---|---|---|---|"]
    for p in page1[:25]:
        lines.append(f"| {p['organic_position']} | {p['asin']} | {p.get('brand_name', '')[:18]} | {_cell(p.get('price'))} | {_cell(p.get('rating'))} | "
                     f"{_cell(p.get('review_count'))} | {_cell(p.get('bought_past_month_min'))} | {_cell(p.get('bsr_rank'))} | {p.get('title', '')[:60]} |")

    def kw_table(title: str, rows: list[dict], n: int = 15):
        if not rows:
            return
        lines.extend(["", f"### {title}", "", "| Tier | Score | Conf | Search-freq rank | Amazon rec rank | Impr. share % | Bid (median) | Keyword |", "|---|---|---|---|---|---|---|---|"])
        for k in rows[:n]:
            lines.append(f"| {k.get('demand_tier') or '-'} | {_cell(k.get('demand_score'))} | {_cell(k.get('confidence'))} | {_cell(k.get('search_frequency_rank'))} | "
                         f"{_cell(k.get('rec_rank'))} | {_cell(k.get('impression_share'))} | {_cell(k.get('bid_median'))} | {k['keyword']} |")

    if candidates:
        lines += ["", "## Keywords", "",
                  "Demand score blends Brand Analytics search-frequency rank, Amazon's keyword recommendations (impression rank/share, "
                  "recommendation rank), estimated total ad impressions, page-1 unit floors and listing-copy prevalence; `Conf` is the share of "
                  "signal weight that was actually present. No column is a search-volume number."]
        kw_table("On-topic (contain the whole seed keyword)", [k for k in candidates if k.get("seed_overlap") == "all"])
        kw_table("Partial overlap", [k for k in candidates if k.get("seed_overlap") == "any"])
        kw_table("Related terms (category / attribute demand)", [k for k in candidates if k.get("seed_overlap") == "none"], 10)
    if analysis:
        lines += ["", "## Competitive analysis (LLM)", "", analysis]
    lines += ["", "---", "", "Generated by amazon-analyst. Research use only: Amazon's Conditions of Use prohibit automated data collection; "
              "keep runs small and infrequent, and never resell or republish scraped data."]
    return "\n".join(lines) + "\n"


def write_report(run: dict, text: str) -> Path:
    d = config.OUTPUT_DIR / _slug(run["keyword"])
    d.mkdir(parents=True, exist_ok=True)
    path = d / f"{datetime.now().strftime('%Y-%m-%d_%H%M')}_run{run['id']}.md"
    path.write_text(text, encoding="utf-8")
    return path
